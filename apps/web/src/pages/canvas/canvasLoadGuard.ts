/**
 * 画布「整份覆盖保存」的准入判据。
 *
 * ⭐⭐⭐ 2026-10-26 生产取证：**为什么「有节点的历史画布」进去是空的**。
 *
 * 事故链（三段都有生产证据，不是推测）：
 *
 * ① **连接被占满**（根因）
 *    画布页的会话级常驻订阅 `/api/agent/runs/events`，**同一个 thread 被同时开了 6 条**，
 *    6 = Chrome 同源 HTTP/1.1 的连接上限 ⇒ 之后的普通请求**排队、根本没离开浏览器**。
 *
 * ② **画布数据拿不到 ⇒ 页面显示为空**
 *    `loadSession()` 里 `await api.get('/sessions/<id>')` 永不 settle
 *    ⇒ 节点数组停在初始空态 ⇒ **用户看到「画布是空的」**；
 *    而且**连报错都没有**（catch 分支也没走到，因为请求根本没结束）。
 *
 * ③ **空画布被写回服务端 ⇒ 真画布被抹掉** ⭐ 本文件要防的就是这一步
 *    `saveCanvas()` 是**整份覆盖 PUT**（`PUT /sessions/:id` 带完整 canvasData），
 *    且**没有「画布尚未加载成功」的守卫**。
 *    而自动保存的触发点很密：视口 tracker（`viewportChange` 防抖后）、
 *    生成记录回填、回合收尾后的轮询……
 *    ⇒ 连接一恢复，**第一个挤出去的请求很可能就是这份「空画布 PUT」**
 *    ⇒ 服务端真画布被抹掉 ⇒ **下次进来就是真的空了**（不再只是"看不见"）。
 *
 * ⇒ 结论：**「画布为空」不是显示 bug，是「请求被饿死」+「空覆盖保存」两件事叠加。**
 *   连接侧修复（订阅收敛到 1 条）解决 ①②；**本守卫解决 ③，两者必须同批上线。**
 *
 * 判据设计：
 * - 「未成功加载」= 状态不是 `loaded`（`idle` / `loading` / `failed` 都算）
 *   —— 此时本地画布**不完整**，任何整份 PUT 都是残缺覆盖；
 * - 「新建的空画布」不在此列：它的加载会**成功**（服务端返回空 canvasData）⇒ `loaded` ⇒ 放行；
 * - 被拦下的保存要**延后补做**（加载成功后重跑），否则用户刚画的东西会丢。
 */

/** 画布数据加载状态。 */
export type CanvasLoadState = 'idle' | 'loading' | 'loaded' | 'failed'

/**
 * 是否禁止「整份覆盖保存」。
 *
 * @param state 画布加载状态
 * @returns true = 禁止整份 PUT（本次保存应被延后）
 *
 * ⚠️ 调用方必须把「被拦下的保存」记下来并在加载成功后补做，
 *    否则用户刚画的内容会丢（判据只管「不许覆盖」，不管「补做」）。
 */
export function shouldBlockCanvasOverwrite(state: CanvasLoadState): boolean {
  return state !== 'loaded'
}
